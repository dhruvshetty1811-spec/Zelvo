import { expect, test } from '@playwright/test';

test.use({trace:'off'});
test('separate driver app supports destination search, trip controls and arrival',async({page})=>{
  const errors:string[]=[];const apiCalls:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.url().includes('/api/'))apiCalls.push(r.url());});
  await page.goto('/driver.html');
  await expect(page.getByRole('heading',{name:'Where are we headed?'})).toBeVisible();
  await expect(page.locator('.driver-device')).toBeVisible();
  await page.screenshot({path:'../reports/driver-home-desktop.png',fullPage:true});
  await page.getByLabel('Hospital destination',{exact:true}).fill('My Care Hospital');
  await page.getByRole('button',{name:/Use “My Care Hospital”/}).click();
  await expect(page.getByRole('heading',{name:'My Care Hospital'})).toBeVisible();
  await page.getByRole('button',{name:'Change hospital destination'}).first().click();
  await expect(page.getByLabel('Hospital destination',{exact:true})).toBeFocused();
  await page.getByLabel('Hospital destination',{exact:true}).fill('Victoria');
  await page.getByRole('button',{name:/Victoria Hospital/}).click();
  await expect(page.getByRole('heading',{name:'Victoria Hospital'})).toBeVisible();
  await page.screenshot({path:'../reports/driver-route-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Start trip',exact:true}).click();
  await expect(page.getByText('Simulated priority active')).toBeVisible();
  await expect.poll(async()=>Number(await page.getByRole('progressbar').getAttribute('aria-valuenow'))).toBeGreaterThan(1);
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  const paused=await page.getByRole('progressbar').getAttribute('aria-valuenow');
  await expect(page.getByText('Trip paused')).toBeVisible();
  await page.waitForTimeout(800);
  expect(await page.getByRole('progressbar').getAttribute('aria-valuenow')).toBe(paused);
  await page.getByRole('button',{name:'Show entire route'}).click();
  await expect(page.getByRole('button',{name:'Follow ambulance'})).toBeVisible();
  await page.getByRole('button',{name:'Follow ambulance'}).click();
  await page.screenshot({path:'../reports/driver-trip-desktop.png',fullPage:true});
  for(const width of [390,360]){
    await page.setViewportSize({width,height:844});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
    expect(await page.locator('.driver-device').evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth;})).toBeTruthy();
    await expect(page.getByRole('button',{name:'End trip',exact:true})).toBeVisible();
    await page.screenshot({path:`../reports/driver-trip-mobile-${width}.png`,fullPage:true});
  }
  await page.getByRole('button',{name:'End trip',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('button',{name:'Continue trip'})).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(page.getByRole('dialog').getByRole('button',{name:'End trip',exact:true})).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'End trip',exact:true})).toBeFocused();
  await page.getByRole('button',{name:'Resume',exact:true}).click();
  await page.getByLabel('Demo speed').selectOption('32');
  await expect(page.getByRole('heading',{name:'You’ve arrived.'})).toBeVisible({timeout:25_000});
  await page.screenshot({path:'../reports/driver-arrival-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Start a new trip'}).click();
  await page.getByLabel('Hospital destination',{exact:true}).fill('Emergency Department');
  await page.getByLabel('Hospital destination',{exact:true}).press('Enter');
  await page.getByRole('button',{name:'Start trip',exact:true}).click();
  await page.getByRole('button',{name:'End trip',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'End trip',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Where are we headed?'})).toBeVisible();
  await expect(page.getByLabel('Hospital destination',{exact:true})).toHaveValue('');
  await page.screenshot({path:'../reports/driver-home-mobile-360.png',fullPage:true});
  expect(errors).toEqual([]);expect(apiCalls).toEqual([]);
});
